"""Benchmark report: python -m eval.run --rerun [--ref COMMIT ...] [--skip-current] [--readme README.md]"""

from __future__ import annotations

import argparse
import csv
import io
import json
import os
import re
import subprocess
import sys
import tarfile
import tempfile
import time
from pathlib import Path

from eval.accuracy import head_to_head, repeatability, score_room

ROOT = Path(__file__).resolve().parents[1]
README_START = "<!-- benchmark:start (generated by python -m eval.run; do not edit) -->"
README_END = "<!-- benchmark:end -->"


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def pipeline_tree(ref: str | None, tmp: Path) -> Path:
    """The working tree, or a clean export of `ref` so older pipeline versions can be re-run exactly."""
    if ref is None:
        return ROOT
    tree = tmp / ref
    if not tree.is_dir():
        archive = subprocess.run(["git", "archive", "--format=tar", ref], cwd=ROOT, capture_output=True, check=True)
        with tarfile.open(fileobj=io.BytesIO(archive.stdout)) as tar:
            tar.extractall(tree, filter="data")
    return tree


def run_pipeline(tree: Path, capture: Path, out: Path) -> tuple[int, float]:
    t0 = time.perf_counter()
    proc = subprocess.run(
        [sys.executable, "-m", "pipeline.cli", "run", "--capture", str(capture), "--out", str(out), "--tier", "auto"],
        cwd=tree, env={**os.environ, "MPLBACKEND": "Agg", "PYTHONPATH": str(tree)}, capture_output=True, text=True,
    )
    return proc.returncode, time.perf_counter() - t0


def fmt_error(name: str, error: float, truth: float) -> str:
    rel = 100 * error / truth
    if name.startswith("Floor area"):
        return f"{error:+.2f} m² ({rel:+.1f} %)"
    return f"{100 * error:+.1f} cm ({rel:+.1f} %)"


def fmt_gate(tol) -> str:
    if tol is None:
        return "—"
    mode, value = tol
    return f"±{100 * value:g} cm" if mode == "abs" else f"±{100 * value:g} %"


def fmt_result(row) -> str:
    if row.passed is None:
        return "—"
    if row.passed:
        return "pass"
    unit = "cm" if row.tolerance[0] == "abs" else "%"
    return f"miss by {100 * row.miss:.1f} {unit}"


def fmt_interval(row) -> str:
    if row.lo is None or row.hi is None:
        return f"{row.value:.3f} (no interval)"
    return f"{row.value:.3f} [{row.lo:.3f}, {row.hi:.3f}]"


def score_plan(plan: dict, gt: dict) -> list[tuple[str, list, dict]]:
    tier = plan.get("input_tier", "lidar")
    rooms = {r["room_id"]: r for r in plan.get("rooms", [])}
    scored = []
    for room_id in sorted(gt.get("ceiling_height_cm", {}) | gt.get("wall_lengths_cm", {})):
        if room_id in rooms:
            rows, openings = score_room(rooms[room_id], gt, room_id, tier)
            scored.append((room_id, rows, openings))
    return scored


def all_rows(scored) -> list:
    return [r for _, rs, ops in scored for r in rs + ops.get("rows", [])]


def summary_row(label: str, scored) -> str:
    rows = all_rows(scored)
    walls = [r for r in rows if r.name.startswith("Wall")]
    find = {r.name: r for r in rows}
    worst = max(walls, key=lambda r: abs(r.error / r.truth), default=None)
    cells = [
        f"{100 * worst.error / worst.truth:+.1f} %" if worst else "—",
        fmt_error("Ceiling", find["Ceiling height"].error, find["Ceiling height"].truth) if "Ceiling height" in find else "—",
        f"{100 * find['Floor area (m²)'].error / find['Floor area (m²)'].truth:+.1f} %" if "Floor area (m²)" in find else "—",
        "; ".join(f"{ops['hits']} of {ops['taped']} within 2 cm, {ops['phantom']} phantom" for _, _, ops in scored if ops) or "—",
        f"{sum(r.covered for r in rows)} of {len(rows)}",
    ]
    return f"| {label} | " + " | ".join(cells) + " |"


def headline(label: str, scored) -> str:
    geometry = [r for _, rs, _ in scored for r in rs]
    if not geometry:
        return f"- {label}: nothing to score."
    worst = min(r.accuracy for r in geometry)
    text = (f"- {label}: walls, ceiling and floor area are within {100 - worst:.1f} % of the tape value "
            f"({worst:.1f} % accuracy or better on each); {sum(bool(r.passed) for r in geometry)} of "
            f"{len(geometry)} strict gates pass")
    for _, _, ops in scored:
        if ops:
            text += f"; openings {ops['hits']} of {ops['taped']} within 2 cm ({ops['phantom']} phantom)"
    return text + "."


def capture_section(title: str, scored, seconds: float | None) -> list[str]:
    lines = [f"## {title}", ""]
    if seconds is not None:
        lines += [f"Pipeline run: {seconds:.0f} s.", ""]
    covered = total = 0
    for _, rows, openings in scored:
        lines += [
            "| Measurement | Tape | Ours [90 % interval] | Error | Accuracy | Gate | Result | Tape inside interval |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for row in rows + openings.get("rows", []):
            lines.append(
                f"| {row.name} | {row.truth:.3f} | {fmt_interval(row)} | {fmt_error(row.name, row.error, row.truth)} "
                f"| {row.accuracy:.1f} % | {fmt_gate(row.tolerance)} | {fmt_result(row)} | {'yes' if row.covered else 'no'} |"
            )
            covered += row.covered
            total += 1
        lines.append("")
        if openings:
            missed = ", ".join(name for name, _ in openings["undetected"])
            lines += [
                f"Openings: {openings['found']} found, {openings['taped']} taped; {openings['hits']} within 2 cm, "
                f"{openings['missed']} missed{f' (not detected: {missed})' if missed else ''}, "
                f"{openings['phantom']} phantom. Score {openings['hits']} / ({openings['taped']} + {openings['phantom']}) "
                f"= {100 * openings['rate']:.0f} % (gate ≥ 85 %): {'pass' if openings['passed'] else 'miss'}.",
                "",
            ]
    lines += [f"Tape value inside the 90 % interval: {covered} of {total} measurements.", ""]
    return lines


def compare(app: dict, scored) -> dict:
    rows = next((rs + ops.get("rows", []) for room_id, rs, ops in scored if room_id == app.get("room_id", room_id)), [])
    undetected = next((ops.get("undetected", []) for room_id, _, ops in scored if room_id == app.get("room_id", room_id)), [])
    return head_to_head(rows, undetected, app.get("lengths_m", {}))


def head_to_head_section(app: dict, scored) -> list[str]:
    h2h = compare(app, scored)
    name = f"{app['app']} {app['version']}"
    lines = [
        f"### Head-to-head: {name}",
        "",
        f"| Measurement | Tape | Ours | {name} | Our error | Their error | Result |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in h2h["rows"]:
        ours = f"{r['ours']:.3f}" if r["ours"] is not None else "not detected"
        our_err = f"{100 * (r['ours'] - r['truth']):+.1f} cm" if r["ours"] is not None else "—"
        lines.append(
            f"| {r['name']} | {r['truth']:.3f} | {ours} | {r['theirs']:.3f} "
            f"| {our_err} | {100 * (r['theirs'] - r['truth']):+.1f} cm | {r['result']} |"
        )
    gate = "meets the brief's 70 % gate" if h2h["passed"] else "the brief's gate is 70 %"
    lines += [
        "",
        f"Beat or tie on {h2h['beat_or_tie']} of {len(h2h['rows'])} measurements (tie = errors within 3 mm; {gate}). "
        f"Their values: {app['source']}.",
    ]
    ours_area = next((r for r in all_rows(scored) if r.name.startswith("Floor area")), None)
    if ours_area is not None and app.get("floor_area_m2") is not None:
        their_rel = 100 * (app["floor_area_m2"] - ours_area.truth) / ours_area.truth
        lines.append(f"Floor area: ours {100 * ours_area.error / ours_area.truth:+.1f} %, {name} {their_rel:+.1f} % "
                     "(shown for reference; the 3 mm tie rule applies to lengths).")
    if app.get("not_compared"):
        lines.append(f"Recorded but not compared: {app['not_compared']}.")
    return lines + [""]


def readme_block(title: str, scored, app: dict | None) -> list[str]:
    rows = all_rows(scored)
    theirs = (app or {}).get("lengths_m", {})
    area_theirs = (app or {}).get("floor_area_m2")
    name = f"{app['app']} {app['version']}" if app else None
    head = f"| {title} | Tape | Ours [90 % interval] | Our error |" + (f" {name} | Their error |" if app else "")
    lines = [head, "|---|---|---|---|" + ("---|---|" if app else "")]
    entries = [(r.name, r.truth, fmt_interval(r), fmt_error(r.name, r.error, r.truth)) for r in rows]
    entries += [(name, truth, "not detected", "—") for _, _, ops in scored for name, truth in ops.get("undetected", [])]
    for name_, truth, ours, our_error in entries:
        line = f"| {name_} | {truth:.3f} | {ours} | {our_error} |"
        if app:
            value = area_theirs if name_.startswith("Floor area") else theirs.get(name_)
            line += (f" {value:.3f} | {fmt_error(name_, value - truth, truth)} |" if value is not None else " — | — |")
        lines.append(line)
    gates = [f"{r.name} {fmt_gate(r.tolerance)}: {fmt_result(r)}" for r in rows if r.tolerance]
    for _, _, ops in scored:
        if ops:
            gates.append(f"openings ≥ 85 % within 2 cm: {100 * ops['rate']:.0f} % ({'pass' if ops['passed'] else 'miss'})")
    if app:
        h2h = compare(app, scored)
        gates.append(f"head-to-head: {h2h['beat_or_tie']} of {len(h2h['rows'])} beat or tie (gate 70 %)")
    return lines + ["", "Gates: " + "; ".join(gates) + "."]


def repeat_section(groups) -> list[str]:
    lines = ["## Repeatability", ""]
    for (room, tier, label), items in sorted(groups.items()):
        for i in range(len(items)):
            for j in range(i + 1, len(items)):
                (id_a, plan_a), (id_b, plan_b) = items[i], items[j]
                rep = repeatability(plan_a["rooms"][0], plan_b["rooms"][0])
                deltas = ", ".join(f"{100 * w['delta']:.1f}" for w in rep["walls"])
                lines.append(
                    f"- {room} ({tier}, {label}), `{id_a}` vs `{id_b}`: wall deltas {deltas} cm "
                    f"(gate 1 cm or 0.5 % each: {'pass' if rep['walls_passed'] else 'miss'}); "
                    f"ceiling spread {100 * rep['ceiling_spread']:.1f} cm "
                    f"(gate 1 cm: {'pass' if rep['ceiling_passed'] else 'miss'})."
                )
    if len(lines) == 2:
        lines.append("No room has two saved captures at the same tier, so repeatability is not reported.")
    return lines + [""]


def write_block(path: Path, block: list[str]) -> None:
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(README_START) + r".*?" + re.escape(README_END), re.S)
    if not pattern.search(text):
        raise SystemExit(f"{path}: add the {README_START} / {README_END} markers first")
    path.write_text(pattern.sub(lambda _: "\n".join([README_START, *block, README_END]), text), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Score pipeline runs against tape ground truth")
    p.add_argument("--captures", type=Path, default=ROOT / "data" / "captures")
    p.add_argument("--runs", type=Path, default=ROOT / "out")
    p.add_argument("--gt", type=Path, default=ROOT / "data" / "ground_truth")
    p.add_argument("--report", type=Path, default=ROOT / "docs" / "BENCHMARK_REPORT.md")
    p.add_argument("--manifest", type=Path, default=ROOT / "data" / "manifest.csv")
    p.add_argument("--apps", type=Path, default=ROOT / "data" / "app_exports", help="<app>_<capture_id>.json files")
    p.add_argument("--readme", type=Path, default=None, help="also write the per-room table into this README")
    p.add_argument("--summary-into", type=Path, action="append", default=[],
                   help="also write the summary table into this file (repeatable)")
    p.add_argument("--rerun", action="store_true", help="run the pipeline on each capture with ground truth first")
    p.add_argument("--ref", action="append", default=[], help="also run the pipeline as of this commit (repeatable)")
    p.add_argument("--skip-current", action="store_true", help="report only the --ref versions")
    args = p.parse_args(argv)

    with args.manifest.open(encoding="utf-8", newline="") as f:
        listed = {row["capture_id"] for row in csv.DictReader(f)}
    gts = {}
    for path in sorted(args.gt.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        if path.stem in listed and data.get("_meta", {}).get("status") == "complete":
            gts[path.stem] = data

    head = git("rev-parse", "--short", "HEAD") or "unknown"
    versions = [(git("rev-parse", "--short", f"{ref}^{{commit}}") or ref, ref) for ref in args.ref]
    if not args.skip_current:
        versions.append((head, None))
    command = ("python -m eval.run" + (" --rerun" if args.rerun else "") + "".join(f" --ref {r}" for r in args.ref)
               + (" --skip-current" if args.skip_current else "") + (f" --readme {args.readme.name}" if args.readme else "")
               + "".join(f" --summary-into {p.as_posix()}" for p in args.summary_into))
    sections: list[str] = []
    summary: list[str] = []
    headlines: list[str] = []
    readme: list[str] = []
    groups: dict = {}
    missing: list[str] = []
    with tempfile.TemporaryDirectory() as tmp:
        for cid, gt in gts.items():
            apps = [json.loads(f.read_text(encoding="utf-8")) for f in sorted(args.apps.glob(f"*_{cid}.json"))]
            for label, ref in versions:
                tag = cid if ref is None else f"{cid}@{label}"
                seconds = None
                if args.rerun:
                    capture = args.captures / cid
                    if not capture.is_dir():
                        missing.append(f"`{cid}`: capture not found under `{args.captures.name}/` (fetch it first)")
                        break
                    code, seconds = run_pipeline(pipeline_tree(ref, Path(tmp)), capture.resolve(), (args.runs / tag).resolve())
                    if code != 0:
                        missing.append(f"`{tag}`: pipeline exited with code {code}")
                        continue
                plan_path = args.runs / tag / "plan.json"
                if not plan_path.is_file():
                    missing.append(f"`{tag}`: no `{plan_path.name}` under `{args.runs.name}/{tag}/`")
                    continue
                plan = json.loads(plan_path.read_text(encoding="utf-8"))
                tier = plan.get("input_tier", "lidar")
                if ref is None:
                    version = f"pipeline at `{label}` (current)"
                elif label.startswith(ref):
                    version = f"pipeline at `{label}`"
                else:
                    version = f"pipeline at `{ref}` (`{label}`)"
                scored = score_plan(plan, gt)
                summary.append(summary_row(f"{cid} ({tier}), {version}", scored))
                headlines.append(headline(f"{cid}, {version}", scored))
                sections += capture_section(f"{cid} ({tier}), {version}", scored, seconds)
                for app in apps:
                    sections += head_to_head_section(app, scored)
                readme += readme_block(f"{gt.get('_meta', {}).get('room', cid)}, {version}", scored,
                                       apps[0] if apps else None) + [""]
                room = gt.get("_meta", {}).get("room")
                if room and len(plan.get("rooms", [])) == 1:
                    groups.setdefault((room, tier, label), []).append((cid, plan))

    summary_table = [
        "| Capture and pipeline version | Worst wall | Ceiling | Floor area | Openings | Tape inside 90 % interval |",
        "|---|---|---|---|---|---|",
        *summary,
    ]
    lines = [
        "# Benchmark report",
        "",
        f"Generated by `{command}` at commit `{head}`. Ground truth is tape-measured "
        "(`data/ground_truth/`, assumptions listed in each file). Every number below comes from this script; "
        "do not edit by hand.",
        "",
        "## Summary",
        "",
        *summary_table,
        "",
        *headlines,
        "",
        *sections,
        *repeat_section(groups),
    ]
    if args.captures.is_dir():
        missing += [
            f"`{d.name}`: no tape ground truth (internal consistency only)"
            for d in sorted(args.captures.iterdir())
            if d.is_dir() and d.name not in gts
        ]
    if missing:
        lines += ["## Not scored", ""] + [f"- {m}" for m in missing] + [""]
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text("\n".join(lines), encoding="utf-8")
    if args.readme:
        write_block(args.readme, readme[:-1])
    for path in args.summary_into:
        write_block(path, summary_table)
    print(args.report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
